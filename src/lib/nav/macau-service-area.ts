/**
 * 服务范围环全集 = 澳门官方环 + 澳大横琴校区官方环 + 横琴口岸澳方管辖区手工环。
 * 后两者是**飞地**：地理上在珠海/横琴，行政上由澳门实施管辖，属服务范围。
 */
export const SERVICE_AREA_RINGS: Ring[] = [...MACAU_ADMIN_RINGS, ...MACAU_UNI_RINGS, HENGQIN_PORT_RING];

/**
 * 边界外容差（米）。取值依据见文件头「数据来源与合规」段：
 * 关闸广场/巴士总站在官方环外 148m，必须收进来；珠海长隆在 1639m，必须排除在外。
 */
export const SERVICE_AREA_PAD_M = 250;

/** 每度纬度的米数（WGS84 平均值，误差对本用途可忽略） */
const M_PER_DEG_LAT = 110540;

/** 每度经度的米数（随纬度收缩） */
function mPerDegLng(latDeg: number): number {
  return 111320 * Math.cos((latDeg * Math.PI) / 180);
}

/**
 * 点到线段的最短距离（米）—— 局部平面近似。
 * 偏移量按**查询点**纬度算米，128m 量级的距离误差 < 0.5m，足够。
 */
function segDistM(lng: number, lat: number, a: [number, number], b: [number, number]): number {
  const kx = mPerDegLng(lat);
  const ax = (a[0] - lng) * kx;
  const ay = (a[1] - lat) * M_PER_DEG_LAT;
  const bx = (b[0] - lng) * kx;
  const by = (b[1] - lat) * M_PER_DEG_LAT;
  const dx = bx - ax;
  const dy = by - ay;
  const len2 = dx * dx + dy * dy;
  // 退化线段（两顶点重合）⇒ 距离即到该点
  let t = len2 > 0 ? -(ax * dx + ay * dy) / len2 : 0;
  t = Math.max(0, Math.min(1, t));
  const cx = ax + t * dx;
  const cy = ay + t * dy;
  return Math.hypot(cx, cy);
}

/** 点到环集边界的最短距离（米）；环集为空 ⇒ `Infinity` */
export function distToRingsM(lng: number, lat: number, rings: Ring[]): number {
  let best = Infinity;
  for (const ring of rings) {
    if (ring.length < 2) continue;
    for (let i = 0; i < ring.length; i++) {
      const d = segDistM(lng, lat, ring[i], ring[(i + 1) % ring.length]);
      if (d < best) best = d;
    }
  }
  return best;
}

/**
 * 坐标是否属于澳门服务范围（含容差）。
 *
 * @param lng GCJ-02 经度（与 `NavPoint` 同口径，**本函数不做坐标转换**）
 * @param lat GCJ-02 纬度
 */
export function inMacauServiceArea(lng: number, lat: number): boolean {
  if (!Number.isFinite(lng) || !Number.isFinite(lat)) return false;
  // 环内：用与地图遮罩同一份射线法实现（`district.ts#isInsideRings`），避免两套判定漂移
  if (isInsideRings(lng, lat, SERVICE_AREA_RINGS)) return true;
  // 环外 250m 内：口岸/边检一带的分界精度与建筑跨线所致，见文件头实测数据
  return distToRingsM(lng, lat, SERVICE_AREA_RINGS) <= SERVICE_AREA_PAD_M;
}
