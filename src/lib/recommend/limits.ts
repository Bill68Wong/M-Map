/**
 * 展示条数上限（src/lib/recommend/limits.ts，2026-11-04 新增）
 *
 * ── 为什么单独一个文件 ────────────────────────────────────────────────
 *   「取几张卡」是**跨 9 处**共用的同一个数字（SSR 首屏 / 刷新接口 / 详情页回查 /
 *   卡片链接 / 高德链路）。散写字面量必然漂移：只要有一处漏改，就会出现
 *   「首屏 6 张、刷新掉回 5 张」——实测过的真实事故形态。
 *   ⇒ 全部引用本文件的常量，禁止再写字面量（断言见 `scripts/test-limits.ts`）。
 *
 * ⚠️ 两个默认张数**并存不合并**：`/recommend`（本地枚举）与 `/nav`（高德规划）
 *   是两个独立产品面，未来单方调参不应牵连对方。当前同值 6 是**用户拍板**的结果
 *   （需求 10），不是「同一个常量」的偷懒。
 */

/** /recommend 链路（本地枚举）默认张数。 */
export const RECOMMEND_LIMIT_DEFAULT = 6;

/** /nav 链路（高德规划）默认张数。与上者同值 —— 用户已拍板两入口一致。 */
export const NAV_LIMIT_DEFAULT = 6;

/**
 * 单卡「后续班车」最多几行（`card.altBuses`）。
 *
 * 口径来源：产品建议值（非用户原话）。依据与 `RouteStack` 的段内并列上限
 * `MAX_PARALLEL = 3` 同量级 —— 都是「同一件事最多给几个选项」。
 * ⚠️ 上限必须落在 `nav-service.ts#backfillAltBuses` **内部**（`m.card.altBuses = dedup`
 *   之前）：若只截主干线、回填时又把并行线加回来，上限形同不存在。
 */
export const ALT_BUSES_MAX = 3;

/**
 * 详情页「另有 N 个下车点」最多列几个。
 *
 * 口径来源：产品建议值 —— 同一条线同一上车站的候选下车点极少超过 4 个
 * （`STOP_PRIORITY` 归并后更少），超过 4 个说明数据脏，详情页不该无上限铺开。
 */
export const ALIGHT_OTHERS_MAX = 4;
